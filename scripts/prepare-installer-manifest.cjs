const { readdir, mkdir, writeFile, copyFile } = require('node:fs/promises')
const { join, resolve, relative, dirname } = require('node:path')

// Compile the package's own file names into the uninstaller. A runtime manifest
// could be edited to delete arbitrary paths, so removal never reads user files.
async function generateManifest(appOutDir, outputPath) {
  // The publisher and NSIS target add these after the afterPack callback.
  const files = new Set(['resources/app-update.yml', 'resources/elevate.exe', 'uninstallerIcon.ico'])
  const directories = new Set(['resources'])
  async function walk(directory) {
    for (const entry of await readdir(directory, { withFileTypes: true })) {
      const absolute = join(directory, entry.name)
      const name = relative(appOutDir, absolute).replaceAll('\\', '/')
      if (name.toLowerCase() === 'outputs' || name.toLowerCase().startsWith('outputs/')) continue
      if (entry.isSymbolicLink()) throw new Error(`Installer manifest cannot contain symbolic links: ${name}`)
      if (entry.isDirectory()) { directories.add(name); await walk(absolute) }
      else if (entry.isFile()) files.add(name)
    }
  }
  await walk(appOutDir)
  const encode = name => {
    if (!name || name.startsWith('/') || name.split('/').some(part => !part || part === '..') || /[\r\n"\0]/.test(name)) throw new Error(`Invalid installer file name: ${name}`)
    return name.replaceAll('$', '$$').replaceAll('/', '\\')
  }
  const lines = ['; Generated by prepare-installer-manifest.cjs. Do not edit.', '!macro MuxivraManagedFiles Action']
  for (const name of [...files].sort()) lines.push(`  !insertmacro \${Action} "${encode(name)}"`)
  lines.push('  !insertmacro ${Action} "${UNINSTALL_FILENAME}"', '!macroend', '', '!macro MuxivraManagedDirectories Action')
  for (const name of [...directories].sort((a, b) => b.split('/').length - a.split('/').length || b.localeCompare(a))) lines.push(`  !insertmacro \${Action} "${encode(name)}"`)
  lines.push('!macroend', '')
  await mkdir(dirname(outputPath), { recursive: true })
  await writeFile(outputPath, lines.join('\n'), 'utf8')
}

module.exports = async context => {
  if (context.electronPlatformName !== 'win32') return
  // NSIS normally adds this after packaging starts, racing the ZIP target.
  // Prepare it before either target reads the shared application directory.
  const { getNsisElevatePath } = require('app-builder-lib/out/toolsets/windows')
  const config = context.packager.config
  const elevatePath = await getNsisElevatePath(config.toolsets?.nsis, config.nsis?.customNsisBinary)
  await copyFile(elevatePath, join(context.appOutDir, 'resources', 'elevate.exe'))
  await generateManifest(resolve(context.appOutDir), join(context.packager.projectDir, '.runtime', 'installer-managed-files.nsh'))
}
module.exports.generateManifest = generateManifest
