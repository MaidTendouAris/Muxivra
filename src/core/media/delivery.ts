import type { Plan } from '../../shared/types'
import { parseCommand } from '../../shared/delivery-command'
import { filterLibrary } from '../../shared/parameters'

const toggles=new Set(['-hide_banner','-nostats','-n','-vn','-an','-sn','-dn','-noautorotate','-shortest','-bitexact'])
const values=new Set(['-ss','-t','-to','-fs','-map','-map_metadata','-map_chapters','-f','-vf','-af','-preset','-crf','-cq','-qp','-rc','-qp_i','-qp_p','-minrate','-maxrate','-bufsize','-qmin','-qmax','-qcomp','-global_quality','-g','-bf','-refs','-keyint_min','-ar','-ac','-sample_fmt','-compression_level','-r','-fps_mode','-pix_fmt','-colorspace','-color_primaries','-color_trc','-color_range','-movflags','-x264-params','-x265-params','-loop','-quality','-hwaccel','-hwaccel_output_format','-hwaccel_device','-threads','-probesize','-analyzeduration','-gpu','-metadata','-disposition','-max_muxing_queue_size','-avoid_negative_ts','-fflags','-flags','-tag','-profile','-tune','-level','-c','-b','-q','-frames','-threads'])
function validateFilter(value:string,original:string|undefined){
  if(value===original)return
  // File-reading filters must be selected through the granted subtitle input.
  const names=new Set(filterLibrary.filter(f=>f.name!=='libplacebo').map(f=>f.name))
  const parts=value.split(/(?<!\\),/)
  if(parts.some(part=>!names.has(part.split('=')[0])||/[;\[\]'"\\]/.test(part)||/(?:file|path|command|model|shader|lut|url)\s*=/i.test(part)))throw new Error('自定义滤镜仅支持当前滤镜库的内联参数；文件输入请通过页面选择')
}
export function editedDeliveryArgs(plan:Plan,command:string):string[]{
  const tokens=parseCommand(command),executable=tokens.shift()!
  if(executable.toLowerCase()!==plan.engine.ffmpegPath.toLowerCase())throw new Error('请使用当前配置的 FFmpeg 引擎')
  if(tokens.pop()!==plan.outputPath)throw new Error('输出路径请在交付页修改后重新生成命令')
  const expectedInputs=plan.args.flatMap((arg,i)=>arg==='-i'?[plan.args[i+1]]:[]),inputs:string[]=[]
  const result:string[]=[];let progress=0,formats=0
  for(let i=0;i<tokens.length;i++){
    const flag=tokens[i],base=flag.replace(/:[vasdt](?::\d+)?$/,'')
    if(toggles.has(flag)){result.push(flag);continue}
    const value=tokens[++i];if(value===undefined)throw new Error(`参数 ${flag} 缺少值`)
    if(flag==='-i'){if(result.at(-4)!=='-protocol_whitelist'||result.at(-2)!=='-format_whitelist')throw new Error('每个输入文件之前需要保留协议与格式限制');inputs.push(value);result.push(flag,value);continue}
    if(['-protocol_whitelist','-format_whitelist','-progress'].includes(flag)){
      const expected=plan.args.flatMap((f,index)=>f===flag?[plan.args[index+1]]:[])
      const used=result.filter(f=>f===flag).length
      if(value!==expected[used])throw new Error(`请保留应用管理的 ${flag} 参数`)
      if(flag==='-progress')progress++
    }else if(!values.has(flag)&&!values.has(base)){
      // Preserve engine-specific options already generated by the full parameter editor.
      if(!plan.args.includes(flag))throw new Error(`未支持的命令参数 ${flag}；请使用完整参数页配置编码器专用选项`)
    }
    if(flag==='-vf'||flag==='-af')validateFilter(value,plan.args[plan.args.indexOf(flag)+1])
    if(flag==='-f'){formats++;if(inputs.length!==expectedInputs.length||value!==plan.args[plan.args.lastIndexOf('-f')+1])throw new Error('输出格式请在封装页面修改')}
    if(/[\x00-\x1f]/.test(value)&&!(base==='-metadata'&&value.startsWith('lyrics=')&&!/[\x00-\x08\x0b\x0c\x0e-\x1f]/.test(value)))throw new Error('参数包含控制字符')
    result.push(flag,value)
  }
  if(JSON.stringify(inputs)!==JSON.stringify(expectedInputs))throw new Error('输入文件请通过文件选择或字幕页面修改')
  for(const flag of ['-protocol_whitelist','-format_whitelist'])if(result.filter(v=>v===flag).length!==plan.args.filter(v=>v===flag).length)throw new Error(`请保留应用管理的 ${flag} 参数`)
  if(progress!==1||!result.includes('-n')||formats!==1)throw new Error('请保留进度输出、输出格式及拒绝覆盖参数')
  return [...result,plan.outputPath]
}

export function deliveryDuration(args:string[],durationMs:number):number{
  const seconds=(text:string)=>text.split(':').reduce((sum,value)=>sum*60+Number(value),0)
  const starts=args.flatMap((flag,i)=>flag==='-ss'?[seconds(args[i+1])]:[]),start=starts.reduce((sum,value)=>sum+value,0)
  const limits=args.flatMap((flag,i)=>flag==='-t'?[seconds(args[i+1])]:flag==='-to'?[seconds(args[i+1])-start]:[])
  const duration=Math.min(durationMs/1000-start,...limits)
  return Number.isFinite(duration)&&duration>=0?duration*1000:durationMs
}
